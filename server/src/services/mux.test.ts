import { beforeEach, describe, expect, it, vi } from 'vitest';

import { mux, resetMux } from '../../../test/mux';
import { installFakeStrapi } from '../../../test/strapi';
import { UploadConfig } from '../../../types/shared-types';
import pluginPkg from '../../../package.json';
import muxService from './mux';

vi.mock('@mux/ts', async () => ({ default: (await import('../../../test/mux')).MuxMock }));

const config = (overrides: Record<string, unknown> = {}) =>
  UploadConfig.parse({ autogenerated_captions_languages: [{ code: 'en', isSourceLanguage: true }], ...overrides });

beforeEach(() => {
  installFakeStrapi();
  resetMux();
  mux.client.video.uploads.create.mockResolvedValue({ id: 'upl_1', url: 'https://storage.example/upload' });
  mux.client.video.assets.create.mockResolvedValue({ id: 'ast_1' });
});

describe('Mux client', () => {
  it('is built so the SDK never repeats a request on its own', async () => {
    await muxService().getAssetById('ast_1');

    expect(mux.options).toHaveLength(1);
    expect(mux.options[0]).toMatchObject({
      tokenId: 'test-token-id',
      tokenSecret: 'test-token-secret',
      maxRetries: 0,
      defaultHeaders: { 'x-source-platform': `Strapi CMS | ${pluginPkg.version}` },
    });
  });
});

describe('uploads', () => {
  it('creates a direct upload with inputs and playback_policies', async () => {
    await muxService().getDirectUploadUrl({ config: config({ signed: true }), storedTextTracks: [] });

    const [request] = mux.client.video.uploads.create.mock.calls[0];
    expect(request.new_asset_settings).toMatchObject({
      inputs: [{ generated_subtitles: [expect.objectContaining({ language_code: 'en' })] }],
      playback_policies: ['signed'],
    });
    expect(request.new_asset_settings).not.toHaveProperty('input');
    expect(request.new_asset_settings).not.toHaveProperty('playback_policy');
    expect(request.new_asset_settings).not.toHaveProperty('directives');
  });

  it('creates an asset from a URL with inputs and playback_policies', async () => {
    await muxService().createRemoteAsset({
      config: config({ upload_type: 'url' }),
      storedTextTracks: [],
      url: 'https://videos.example/clip.mp4',
    });

    const [request] = mux.client.video.assets.create.mock.calls[0];
    expect(request).toMatchObject({
      inputs: [expect.objectContaining({ url: 'https://videos.example/clip.mp4' })],
      playback_policies: ['public'],
    });
    expect(request).not.toHaveProperty('input');
    expect(request).not.toHaveProperty('playback_policy');
    expect(request).not.toHaveProperty('directives');
  });
});
